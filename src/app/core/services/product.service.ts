  // Service Methods
  getProductById(id: string): Product | undefined {
    return this._products().find((p) => p.id === id || p.slug === id);
  }

  getProductBySlug(slug: string): Product | undefined {
    return this._products().find((p) => p.slug === slug || p.id === slug);
  }

  getProductsByCategory(categoryId: string): Product[] {
    return this._products().filter((p) => p.categoryId === categoryId);
  }

  getRelatedProducts(productId: string, limit = 4): Product[] {
    const target = this.getProductById(productId);
    if (!target) return this._products().slice(0, limit);

    return this._products()
      .filter((p) => p.id !== target.id && p.categoryId === target.categoryId)
      .slice(0, limit);
  }

  addReview(productId: string, review: Omit<Review, 'id' | 'productId' | 'createdAt'>): void {
    const newReview: Review = {
      ...review,
      id: `rev-${Date.now()}`,
      productId,
      createdAt: new Date().toISOString(),
    };

    this._products.update((products) =>
      products.map((p) => {
        if (p.id === productId || p.slug === productId) {
          const existingReviews = p.reviews ?? [];
          const updatedReviews = [newReview, ...existingReviews];
          const newReviewCount = (p.reviewCount ?? 0) + 1;
          const totalRating = updatedReviews.reduce((sum, r) => sum + r.rating, 0);
          const newAvgRating = Math.round((totalRating / updatedReviews.length) * 10) / 10;

          return {
            ...p,
            reviews: updatedReviews,
            reviewCount: newReviewCount,
            rating: newAvgRating,
          };
        }
        return p;
      })
    );
  }

  filterProducts(criteria: ProductFilterCriteria): Product[] {
    let result = [...this._products()];

    if (criteria.categoryId) {
      result = result.filter((p) => p.categoryId === criteria.categoryId);
    }
    if (criteria.brand) {
      result = result.filter(
        (p) => p.brand.toLowerCase() === criteria.brand?.toLowerCase()
      );
    }
    if (criteria.minPrice !== undefined && criteria.minPrice > 0) {
      result = result.filter((p) => p.price >= (criteria.minPrice ?? 0));
    }
    if (criteria.maxPrice !== undefined && criteria.maxPrice < Infinity) {
      result = result.filter((p) => p.price <= (criteria.maxPrice ?? Infinity));
    }
    if (criteria.minRating !== undefined && criteria.minRating > 0) {
      result = result.filter((p) => p.rating >= (criteria.minRating ?? 0));
    }
    if (criteria.inStockOnly) {
      result = result.filter((p) => (p.inStock ?? true) && p.stock > 0);
    }
    if (criteria.searchQuery && criteria.searchQuery.trim().length > 0) {
      const q = criteria.searchQuery.toLowerCase().trim();
      result = result.filter(
        (p) =>
          p.name.toLowerCase().includes(q) ||
          p.brand.toLowerCase().includes(q) ||
          p.description.toLowerCase().includes(q) ||
          (p.sku && p.sku.toLowerCase().includes(q))
      );
    }

    if (criteria.sortBy) {
      switch (criteria.sortBy) {
        case 'price-asc':
          result.sort((a, b) => a.price - b.price);
          break;
        case 'price-desc':
          result.sort((a, b) => b.price - a.price);
          break;
        case 'rating':
          result.sort((a, b) => b.rating - a.rating);
          break;
        case 'newest':
          result.sort(
            (a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime()
          );
          break;
        case 'name':
          result.sort((a, b) => a.name.localeCompare(b.name));
          break;
      }
    }

    return result;
  }

  getPriceRange(): { min: number; max: number } {
    const prices = this._products().map((p) => p.price);
    if (prices.length === 0) return { min: 0, max: 5000 };
    return {
      min: Math.floor(Math.min(...prices)),
      max: Math.ceil(Math.max(...prices)),
    };
  }

  getAvailableBrands(categoryId?: string): string[] {
    const list = categoryId
      ? this._products().filter((p) => p.categoryId === categoryId)
      : this._products();
    const set = new Set(list.map((p) => p.brand));
    return Array.from(set).sort();
  }

